"""plan_v3 E10: XGBoost + source-kNN(k=5) CDF-average ensemble. Target VAL only. Writes results/h3/*.json + H3_SUMMARY.md.
Member scores are mapped through each member's empirical CDF on pooled SOURCE val (no target statistics).
Usage: python scripts/h3_ensemble.py   (idempotent)
"""
import glob, json, os, sys, time
import numpy as np, pandas as pd
from scipy import stats
from sklearn.neighbors import NearestNeighbors

ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..")
sys.path.insert(0, os.path.join(ROOT, "src")); sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import nids  # noqa: E402
from run_job import assemble  # noqa: E402
from final_report import holm  # noqa: E402

OUT = os.path.join(ROOT, "results", "h3"); os.makedirs(OUT, exist_ok=True)


def lg(X):
    return np.log1p(np.maximum(X, 0.0))


def cdf(ref):
    r = np.sort(ref)
    return lambda x: np.searchsorted(r, x, side="right") / len(r)


def run(t, s):
    f = os.path.join(OUT, f"E10_ens_{t}_s{s}.json")
    if os.path.exists(f):
        return json.load(open(f))
    t0 = time.time()
    spec = {"protocol": "lodo", "target": t, "n_per_source": 100000, "n_val_per_source": 60000, "eval_split": "val"}
    tr, va, te = assemble(spec, s)
    cols = [c for c in nids.feature_cols(te) if c != "_env"]
    cfg = json.load(open(os.path.join(ROOT, "results", f"tune_lodo_xgb_{t}.json")))["best_cfg"]
    m = nids.make_model("xgb", cfg, s); m.fit(tr[cols].to_numpy(np.float32), tr.Label.to_numpy())
    x_va = m.predict_proba(va[cols].to_numpy(np.float32))[:, 1]; x_te = m.predict_proba(te[cols].to_numpy(np.float32))[:, 1]
    # kNN member: 20k/source train subsample drawn exactly as E7 (same assemble call with n_per_source=20000)
    trk, _, _ = assemble({**spec, "n_per_source": 20000, "n_val_per_source": 20000}, s)
    Xk = lg(trk[cols].to_numpy(np.float64)); mu, sd = Xk.mean(0), Xk.std(0) + 1e-6
    nn = NearestNeighbors(n_neighbors=5, n_jobs=-1).fit((Xk - mu) / sd); yk = trk.Label.to_numpy()
    def ks(d):
        dist, ind = nn.kneighbors((lg(d[cols].to_numpy(np.float64)) - mu) / sd); w = 1 / (dist + 1e-6)
        return (w * yk[ind]).sum(1) / w.sum(1)
    k_va, k_te = ks(va), ks(te)
    Fx, Fk = cdf(x_va), cdf(k_va)
    e_va, e_te = (Fx(x_va) + Fk(k_va)) / 2, (Fx(x_te) + Fk(k_te)) / 2
    yva, yte = va.Label.to_numpy(), te.Label.to_numpy()
    out = {"target": t, "seed": s}
    for name, pv, pt in (("xgb", x_va, x_te), ("knn5", k_va, k_te), ("ens", e_va, e_te)):
        thr, fva = nids.best_threshold(yva, pv); r = nids.metrics(yte, pt, thr); r["src_val_macro_f1"] = fva; out[name] = r
    c1 = json.load(open(os.path.join(ROOT, "results", f"E1_lodo_xgb_{t}_s{s}.json")))
    out["xgb_reproduces_cycle1"] = abs(out["xgb"]["auroc"] - c1["auroc"]) < 1e-6; out["wall_s"] = time.time() - t0
    json.dump(out, open(f + ".tmp", "w"), indent=1); os.replace(f + ".tmp", f)
    print(f"{t} s{s} xgb={out['xgb']['macro_f1']:.4f} knn={out['knn5']['macro_f1']:.4f} ens={out['ens']['macro_f1']:.4f} "
          f"(repro={out['xgb_reproduces_cycle1']}, {out['wall_s']:.0f}s)", flush=True)
    return out


def main():
    R = [run(t, s) for t in ["UNSW", "TON", "CIC", "BOT"] for s in [0, 1, 2]]
    d = pd.DataFrame([{"target": r["target"], "seed": r["seed"], **{f"{k}_f1": r[k]["macro_f1"] for k in ("xgb", "knn5", "ens")},
                       **{f"{k}_auroc": r[k]["auroc"] for k in ("xgb", "knn5", "ens")}} for r in R])
    p = d[d.target.isin(["UNSW", "TON", "CIC"])]
    diff = (p.ens_f1 - p.xgb_f1).values
    w = stats.wilcoxon(diff) if np.any(diff != 0) else None
    import csv
    n_var = sum(1 for _ in open(os.path.join(ROOT, "state", "variants_tried.csv"))) - 1
    p_raw = float(w.pvalue) if w else 1.0
    p_holm = float(holm(np.array([p_raw] + [1.0] * (n_var - 1)))[0])
    prim = p.groupby("seed")[["xgb_f1", "knn5_f1", "ens_f1"]].mean()
    L = ["# H3 ensemble test (auto-generated by scripts/h3_ensemble.py; target VAL; seeds 0-2)", "",
         d.groupby("target").mean(numeric_only=True).drop(columns="seed").round(4).reset_index().to_markdown(index=False), "",
         "Primary metric per seed (mean UNSW/TON/CIC):", "", prim.round(4).reset_index().to_markdown(index=False), "",
         f"Paired ens - xgb over {len(diff)} units: mean {diff.mean():.4f}, Wilcoxon p {p_raw:.4f}, Holm p {p_holm:.4f} "
         f"(family = {n_var} variants in variants_tried.csv). Success rule: mean > 0.02 and Holm p < 0.05 -> "
         f"{'MET' if diff.mean() > 0.02 and p_holm < 0.05 else 'NOT MET'}.",
         f"XGBoost member reproduces cycle-1 AUROC on all runs: {all(r['xgb_reproduces_cycle1'] for r in R)}"]
    open(os.path.join(OUT, "H3_SUMMARY.md"), "w").write("\n".join(L) + "\n"); print("\n".join(L[-2:]))


if __name__ == "__main__":
    main()
