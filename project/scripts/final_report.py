#!/usr/bin/env python3
"""Automatic results report from result files only (no LLM).
Writes results/metrics.json, results/statistics.json, tables/*.md|csv, results/RESULTS_SUMMARY.md.
Statistics: paired over (target, seed) units vs the best baseline (chosen by mean primary metric on the SAME split),
Wilcoxon signed-rank + paired t, Cohen's dz, bootstrap 95% CI of mean difference, Holm across all comparisons on that split.
"""
import os, re, json, sys, glob
import numpy as np, pandas as pd
from scipy import stats

R = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
PRIMARY_TARGETS = ["UNSW", "TON", "CIC"]
BASELINES = ["lr", "rf", "lgbm", "xgb", "mlp", "dann", "coral"]


def label(row):
    m = re.search(r"_t(0\.\d+)_", row["job_id"])
    return row["method"] + (f"@{m.group(1)}" if m else "") + (f"#n{int(row['n_train'])}" if row["exp"] == "E3" else "")


def boot_ci(d, n=10000, seed=0):
    rng = np.random.default_rng(seed); d = np.asarray(d)
    bs = rng.choice(d, (n, len(d)), replace=True).mean(1)
    return [float(np.quantile(bs, 0.025)), float(np.quantile(bs, 0.975))]


def holm(ps):
    ps = np.asarray(ps, float); o = np.argsort(ps); m = len(ps); adj = np.empty(m); run = 0
    for k, i in enumerate(o):
        run = max(run, (m - k) * ps[i]); adj[i] = min(1.0, run)
    return adj


def summarise(df, split):
    d = df[df.eval_split == split].copy()
    if d.empty:
        return {}, {}
    d["label"] = d.apply(label, axis=1)
    met = {}
    for (exp, proto, lab, tgt), g in d.groupby(["exp", "protocol", "label", "target"]):
        met.setdefault(f"{exp}|{proto}|{lab}", {})[tgt] = {
            k: {"mean": float(g[k].mean()), "std": float(g[k].std(ddof=1)) if len(g) > 1 else 0.0, "n": int(len(g))}
            for k in ("macro_f1", "auroc", "prauc", "tpr", "fpr", "fit_s", "pred_ms_per_1k", "n_features")}
    # paired statistics on LODO, primary targets
    lo = d[(d.protocol == "lodo") & d.target.isin(PRIMARY_TARGETS) & (d.exp.isin(["E1", "E6", "E2"]) | d.exp.str.startswith("E"))]
    lo = lo[lo.exp != "E3"]
    piv = lo.pivot_table(index=["target", "seed"], columns="label", values="macro_f1")
    piv = piv.dropna(axis=1, thresh=max(1, int(0.9 * len(piv))))
    st = {"split": split, "unit": "(target, seed) pairs over targets " + ",".join(PRIMARY_TARGETS), "comparisons": []}
    base_cols = [c for c in piv.columns if c in BASELINES]
    if base_cols:
        best = max(base_cols, key=lambda c: piv[c].mean()); st["best_baseline"] = best
        comps = []
        for c in piv.columns:
            if c == best:
                continue
            pair = piv[[c, best]].dropna(); diff = (pair[c] - pair[best]).to_numpy()
            if len(diff) < 3:
                continue
            w = stats.wilcoxon(diff) if np.any(diff != 0) else None
            t = stats.ttest_rel(pair[c], pair[best])
            comps.append({"method": c, "vs": best, "n_pairs": int(len(diff)), "mean_diff": float(diff.mean()),
                          "ci95_boot": boot_ci(diff), "cohen_dz": float(diff.mean() / (diff.std(ddof=1) + 1e-12)),
                          "p_wilcoxon": float(w.pvalue) if w else 1.0, "p_ttest": float(t.pvalue),
                          "mean_method": float(pair[c].mean()), "mean_best": float(pair[best].mean())})
        if comps:
            adj = holm([c["p_wilcoxon"] for c in comps])
            for c, a in zip(comps, adj):
                c["p_holm"] = float(a)
        st["comparisons"] = sorted(comps, key=lambda c: -c["mean_diff"])
        st["n_comparisons_holm"] = len(comps)
    return met, st


def main():
    p = os.path.join(R, "results", "raw_results.csv")
    if not os.path.exists(p):
        print("no results yet"); return
    df = pd.read_csv(p).drop_duplicates("job_id", keep="last")
    os.makedirs(os.path.join(R, "tables"), exist_ok=True)
    allm, alls = {}, {}
    for split in ("val", "test"):
        m, s = summarise(df, split)
        if m:
            allm[split] = m; alls[split] = s
    json.dump(allm, open(os.path.join(R, "results", "metrics.json"), "w"), indent=1)
    json.dump(alls, open(os.path.join(R, "results", "statistics.json"), "w"), indent=1)
    # main table: LODO macro-F1 per target (mean±std over seeds) for each split
    L = ["# RESULTS SUMMARY (auto-generated by scripts/final_report.py from results/raw_results.csv)", ""]
    for split, m in allm.items():
        rows = []
        for key, per in m.items():
            exp, proto, lab = key.split("|")
            r = {"exp": exp, "protocol": proto, "method": lab}
            for t in ["UNSW", "TON", "CIC", "BOT"]:
                if t in per:
                    r[t] = f"{per[t]['macro_f1']['mean']:.4f}±{per[t]['macro_f1']['std']:.4f}"
                    r[t + "_auroc"] = round(per[t]["auroc"]["mean"], 4)
            prim = [per[t]["macro_f1"]["mean"] for t in PRIMARY_TARGETS if t in per]
            r["primary_mean3"] = round(float(np.mean(prim)), 4) if len(prim) == 3 else None
            rows.append(r)
        tab = pd.DataFrame(rows).sort_values(["exp", "protocol", "primary_mean3"], ascending=[True, True, False])
        tab.to_csv(os.path.join(R, "tables", f"main_{split}.csv"), index=False)
        open(os.path.join(R, "tables", f"main_{split}.md"), "w").write(tab.to_markdown(index=False))
        L += [f"## Split: {split}  ({'exploration: TARGET val pools' if split == 'val' else 'CONFIRMATION: TARGET test pools'})", "",
              tab.to_markdown(index=False), ""]
        s = alls.get(split, {})
        if s.get("comparisons"):
            L += [f"### Paired comparisons vs best baseline `{s['best_baseline']}` ({s['unit']}; Holm over {s['n_comparisons_holm']})", "",
                  pd.DataFrame(s["comparisons"]).round(4).to_markdown(index=False), ""]
    vt = os.path.join(R, "state", "variants_tried.csv")
    if os.path.exists(vt):
        L += [f"Variants/ideas logged in state/variants_tried.csv: {len(pd.read_csv(vt))}", ""]
    open(os.path.join(R, "results", "RESULTS_SUMMARY.md"), "w").write("\n".join(L))
    print("\n".join(L[:60]))


if __name__ == "__main__":
    main()
