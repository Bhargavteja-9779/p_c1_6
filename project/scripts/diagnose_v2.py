"""Cycle-2 diagnostics (plan_v2, rung 1 of the 6.4 ladder). Uses ONLY saved cycle-1 scores + target VAL
pools (never the test pools). No model training.

D1 per-family ranking: for every E1 arm/target/seed, AUROC of each attack family vs target benign, and recall
   at the source-val threshold (from results/<job>.json).
D4 ranking vs threshold: macro-F1 at the source threshold vs the best possible threshold on target val
   (oracle; analysis only, never used for selection) vs AUROC.
D2 nearest-source-label: for each target attack family, the share of its flows whose 5 nearest neighbours in the
   pooled SOURCE training data (20k/source, log1p + source z-score) are mostly BENIGN. Tests whether missed
   families look like source benign traffic (label-conditional overlap) rather than like source attacks.

Outputs: results/diag_v2/{family_auroc.csv, threshold_vs_ranking.csv, nn_source_label.csv, DIAG_SUMMARY.md}
Usage: python scripts/diagnose_v2.py   (idempotent; ~10 CPU-min)
"""
import glob, json, os, re, sys
import numpy as np, pandas as pd
from sklearn.metrics import roc_auc_score, f1_score
from sklearn.neighbors import NearestNeighbors

ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..")
sys.path.insert(0, os.path.join(ROOT, "src"))
from nids import load, feature_cols, DATASETS  # noqa: E402

OUT = os.path.join(ROOT, "results", "diag_v2"); os.makedirs(OUT, exist_ok=True)
ID = re.compile(r"^(?P<arm>E1_lodo_.+)_(?P<t>UNSW|TON|CIC|BOT)_s(?P<s>\d+)\.npz$")


def macro_f1(y, yhat):
    return f1_score(y, yhat, average="macro", zero_division=0)


def best_thr_f1(y, p):
    qs = np.unique(np.quantile(p, np.linspace(0, 1, 401)))
    return max(macro_f1(y, (p >= q).astype(int)) for q in qs)


def d1_d4():
    fam_rows, thr_rows, pools = [], [], {}
    for f in sorted(glob.glob(os.path.join(ROOT, "results", "scores", "*.npz"))):
        m = ID.match(os.path.basename(f))
        if not m:
            continue
        arm, t, s = m["arm"], m["t"], int(m["s"])
        z = np.load(f); p, y = z["p"].astype(float), z["y"].astype(int)
        if t not in pools:
            pools[t] = load(t, "random", "val")["Attack"].values
        fam = pools[t]
        res = json.load(open(os.path.join(ROOT, "results", os.path.basename(f)[:-4] + ".json")))
        thr = res["threshold"]
        ben = fam == "Benign"
        for a in sorted(set(fam) - {"Benign"}):
            idx = fam == a
            if idx.sum() < 20 or ben.sum() < 20:
                continue
            yy = np.r_[np.zeros(ben.sum()), np.ones(idx.sum())]
            pp = np.r_[p[ben], p[idx]]
            fam_rows.append({"arm": arm, "target": t, "seed": s, "family": a, "n": int(idx.sum()),
                             "share_of_attacks": float(idx.sum() / max(1, (~ben).sum())),
                             "auroc_vs_benign": float(roc_auc_score(yy, pp)),
                             "recall_at_src_thr": float((p[idx] >= thr).mean())})
        thr_rows.append({"arm": arm, "target": t, "seed": s, "auroc": res["auroc"],
                         "f1_src_thr": res["macro_f1"], "f1_oracle_thr": best_thr_f1(y, p),
                         "fpr_src_thr": res["fpr"]})
    fa = pd.DataFrame(fam_rows); fa.to_csv(os.path.join(OUT, "family_auroc.csv"), index=False)
    tr = pd.DataFrame(thr_rows); tr.to_csv(os.path.join(OUT, "threshold_vs_ranking.csv"), index=False)
    return fa, tr


def d2(n_src=20000, n_tgt_fam=500, k=5, seed=0):
    rows = []
    for t in ["UNSW", "TON", "CIC", "BOT"]:
        srcs = [d for d in DATASETS if d != t]
        S = pd.concat([load(d, "random", "train").sample(n_src, random_state=seed) for d in srcs])
        cols = feature_cols(S)
        Xs = np.log1p(np.clip(S[cols].replace([np.inf, -np.inf], 0).fillna(0).values.astype(float), 0, None))
        mu, sd = Xs.mean(0), Xs.std(0) + 1e-6
        nn = NearestNeighbors(n_neighbors=k).fit((Xs - mu) / sd)
        ys = S["Label"].values.astype(int)
        T = load(t, "random", "val")
        for a, g in T.groupby("Attack"):
            g = g.sample(min(len(g), n_tgt_fam), random_state=seed)
            Xt = np.log1p(np.clip(g[cols].replace([np.inf, -np.inf], 0).fillna(0).values.astype(float), 0, None))
            _, ind = nn.kneighbors((Xt - mu) / sd)
            frac_attack_nb = ys[ind].mean(1)
            rows.append({"target": t, "family": a, "n_used": len(g),
                         "share_nn_majority_benign": float((frac_attack_nb < 0.5).mean()),
                         "mean_frac_attack_neighbours": float(frac_attack_nb.mean())})
    d = pd.DataFrame(rows); d.to_csv(os.path.join(OUT, "nn_source_label.csv"), index=False)
    return d


def main():
    fa, tr = d1_d4()
    nn = d2()
    L = ["# Cycle-2 diagnostics (auto-generated by scripts/diagnose_v2.py; target VAL pools; analysis only)", ""]
    for arm in ["E1_lodo_xgb", "E1_lodo_lgbm", "E1_lodo_pen-lgbm"]:
        g = fa[fa.arm == arm].groupby(["target", "family"]).agg(n=("n", "first"), share=("share_of_attacks", "first"),
                                                                 auroc=("auroc_vs_benign", "mean"),
                                                                 recall=("recall_at_src_thr", "mean")).reset_index()
        g = g.merge(nn[["target", "family", "share_nn_majority_benign"]], on=["target", "family"], how="left")
        L += [f"## D1+D2 per-family ({arm}, mean over seeds)", "", g.round(3).to_markdown(index=False), ""]
    t = tr.groupby(["arm", "target"])[["auroc", "f1_src_thr", "f1_oracle_thr", "fpr_src_thr"]].mean().reset_index()
    L += ["## D4 ranking vs threshold (oracle threshold uses target-val labels: diagnostic only)", "",
          t.round(3).to_markdown(index=False), ""]
    g = fa.groupby(["target", "family"]).agg(recall=("recall_at_src_thr", "mean")).reset_index().merge(nn, on=["target", "family"])
    rho = g[["recall", "share_nn_majority_benign"]].corr(method="spearman").iloc[0, 1]
    L += [f"Spearman(recall over all E1 arms, share of family flows whose source neighbours are mostly benign) = {rho:.3f} "
          f"over {len(g)} target families.", ""]
    open(os.path.join(OUT, "DIAG_SUMMARY.md"), "w").write("\n".join(L))
    print("\n".join(L[-2:]))


if __name__ == "__main__":
    main()
